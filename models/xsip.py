from sqlalchemy import Column, String, Integer, Text, DateTime
from sqlalchemy.sql import func
from database import Base


class XSIPRegistration(Base):
    __tablename__ = "xsip_registrations"

    id = Column(Integer, primary_key=True, autoincrement=True)
    amc_code = Column(String(50))
    sch_code = Column(String(20))
    client_code = Column(String(10), index=True)
    bank_ref_no = Column(String(20))
    trans_mode = Column(String(20))
    dp_txn_mode = Column(String(1))
    start_date = Column(String(10))
    frequency_type = Column(String(20))
    frequency_allowed = Column(String(1))
    installment_amount = Column(String(20))
    status = Column(String(1))
    member_code = Column(String(20))
    folio_no = Column(String(15))
    sip_remarks = Column(String(100))
    installment_no = Column(String(10))
    convenience_fee = Column(String(20))
    xsip_mandate_id = Column(String(20))
    sub_broker_code = Column(String(15))
    euin_number = Column(String(20))
    euin_declaration = Column(String(1))
    dpc_flag = Column(String(1))
    first_order_today = Column(String(1))
    isip_mandate = Column(String(15))
    sub_broker_arn = Column(String(20))
    end_date = Column(String(10))
    primary_holder_mobile = Column(String(10))
    primary_holder_email = Column(String(50))
    step_up_required = Column(String(1))
    step_up_start_date = Column(String(10))
    step_up_end_date = Column(String(10))
    step_up_frequency = Column(String(20))
    step_up_amount = Column(String(20))
    filler_1 = Column(String(50))
    filler_2 = Column(String(50))
    filler_3 = Column(String(50))
    filler_4 = Column(String(50))
    filler_5 = Column(String(50))
    reg_id = Column(String(15))
    reg_status = Column(String(15))
    reg_remark = Column(Text)
    member_unique_id = Column(String(25))
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), onupdate=func.now())
